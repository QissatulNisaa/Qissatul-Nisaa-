// Story selector and navigation
function generateStorySelector() {
  const selectorGrid = document.getElementById('storySelector');
  if (!selectorGrid) return;

  selectorGrid.innerHTML = '';

  allStories.forEach((story, index) => {
    const btn = document.createElement('button');
    btn.className = "bg-white border-2 border-purple-300 rounded-xl p-6 text-center hover:bg-purple-50 hover:scale-105 transition";
    btn.innerHTML = `
      <div class="mb-4 flex justify-center">
        ${getWomanIllustration(story.name)}
      </div>
      <div class="font-semibold text-purple-700 text-sm">
        ${story.name}
      </div>
    `;

    btn.onclick = () => showSingleStory(index);
    selectorGrid.appendChild(btn);
  });
}

function getWomanIllustration(name) {
  const imageMap = {
    "Maryam": "../assets/images/maryam.png",
    "Wife of 'Imran": "../assets/images/wifeofimran.png",
    "Wife of Ibrahim": "../assets/images/wifeofibrahim.png",
    "Queen of Sheba": "../assets/images/queenofsheba.png",
    "Mother of Musa": "../assets/images/motherofmusa.png",
    "The Two Women of Madyan": "../assets/images/twowomenmadyan.png",
    "Wife of Pharaoh":"/assets/images/asiyah.png"
  };

  let imageSrc = '../assets/images/women/default.png';

  for (const key in imageMap) {
    if (name.includes(key)) {
      imageSrc = imageMap[key];
      break;
    }
  }

  return `
    <div class="text-center float"
         style="width: 100px; height: 100px;
         display: flex; align-items: center; justify-content: center;
         background: linear-gradient(135deg, #f7e0ee 100%);
         border-radius: 50%;
         box-shadow: 0 10px 30px rgba(168, 85, 247, 0.3);">
         
      <img src="${imageSrc}"
     alt="${name}"
     style="
       width: 100%;
       height: 100%;
       object-fit: cover;
       border-radius: 100%;
     ">

    </div>
  `;
}

let currentStoryIndex = 0;
let currentPageIndex = 0;

function showSingleStory(index) {
  currentStoryIndex = index;
  currentPageIndex = 0;

  document.getElementById('storySelectorWrapper').classList.add('hidden');
  renderBookletPage();
}

function renderBookletPage() {
  const story = allStories[currentStoryIndex];
  const section = story.sections[currentPageIndex];
  const container = document.getElementById('storiesContainer');
  const verseFirst = story.renderOrder === "verse-first";

  container.innerHTML = `
    <button onclick="backToStoryList()" class="mb-6 bg-purple-600 text-white px-6 py-3 rounded-xl">
      ⬅ Back to Story List
    </button>

    <div class="bg-white rounded-2xl shadow-xl p-8 mb-6 fade-in">
      <h2 class="text-3xl font-bold text-purple-800 mb-2">
        ${story.name}
      </h2>

      ${story.fullName ? `<p class="text-sm italic text-gray-500 mb-1">${story.fullName}</p>` : ""}

      <p class="text-sm text-pink-600 mb-4">
        ${story.mentionCount}
      </p>

      <div class="flex flex-wrap gap-2 mb-6">
        ${story.titles.map(t => `
          <span class="bg-purple-100 text-purple-700 text-xs px-3 py-1 rounded-full">${t}</span>
        `).join("")}
      </div>

      <hr class="mb-6">

      <h3 class="text-xl font-semibold text-purple-800 mb-4">
        ${section.title}
      </h3>

      ${section.image ? `
        <div class="flex justify-center mb-6">
          <img 
            src="${section.image.src.startsWith('/') ? section.image.src : '/' + section.image.src}"
            alt="${section.image.alt}"
            class="max-w-md w-full rounded-xl shadow-lg"
          />
        </div>
      ` : ""}

      ${section.background ? `<p class="text-gray-700 italic mb-6">${section.background}</p>` : ""}

      ${verseFirst ? renderVersesFirst(section) : renderContentFirst(section)}

      ${section.postContent ? `
        <div class="story-text text-gray-700">
          ${section.postContent}
        </div>
      ` : ""}

      ${section.postVerses && section.postVerses.length ? `
        <div class="mt-10 border-t pt-6">
          ${section.postVerses.map(v => `
            <div class="mb-8">
              <div class="arabic-text bg-pink-50 p-6 rounded-lg mb-3">
                ${v.arabic}
              </div>
              <p class="italic text-gray-700 mb-2">${v.translation}</p>
              <p class="text-sm text-pink-600">${v.reference}</p>
            </div>
          `).join("")}
        </div>
      ` : ""}
    </div>

    <!-- NAVIGATION BUTTONS -->
    <div class="flex justify-between items-center min-h-[44px]">

      ${currentPageIndex > 0 ? `
        <button onclick="prevPage()" class="px-5 py-2 rounded-lg bg-gray-200">
          ⬅ Previous
        </button>
      ` : `<div></div>`}

      <span class="text-sm text-gray-600">
        Page ${currentPageIndex + 1} / ${story.sections.length}
      </span>

      ${currentPageIndex < story.sections.length - 1 ? `
        <button onclick="nextPage()" class="px-5 py-2 rounded-lg bg-purple-600 text-white">
          Next ➡
        </button>
      ` : `<div></div>`}

    </div>
  `;
}


function renderVersesFirst(section) {
  let html = '';
  
  if (section.verses && section.verses.length) {
    section.verses.forEach(v => {
     html += `
  <div class="mb-10">

    <!-- AYAT QURAN -->
    <div class="arabic-text bg-purple-50 p-6 rounded-lg mb-4">
      ${v.arabic}
    </div>

    <!-- AUDIO TERUS BAWAH AYAT -->
    ${v.audio ? `
      <div class="quran-audio-wrapper mb-4">
        <audio controls preload="metadata" class="quran-audio">
          <source src="${v.audio}" type="audio/mpeg">
          Your browser does not support the audio element.
        </audio>
      </div>
    ` : ""}

    <!-- TRANSLATION -->
    <p class="italic text-gray-700 mb-2">
      ${v.translation}
    </p>

    <!-- REFERENCE -->
    <p class="text-sm text-purple-600 mb-4">
      ${v.reference}
    </p>

    ${v.explanation ? `
      <div class="story-text explanation text-gray-700">
        ${v.explanation}
      </div>
    ` : ""}

  </div>
`;

    });
  }

  if (Array.isArray(section.content)) {
  html += `<div class="story-text text-gray-700">`;
  section.content.forEach(p => {
    html += `<p>${p}</p>`;
  });
  html += `</div>`;
}
 else if (section.content) {
  html += `
  <div class="story-text text-gray-700">
    <p>${section.content}</p>
  </div>
`;
}



  return html;
}

 function renderContentFirst(section) {
  let html = '';

  if (section.content) {
    html += `
      <div class="story-text text-gray-700">
  ${section.content}
</div>
    `;
  }

  if (section.explanation) {
    html += `
      <div class="story-text text-gray-700">
        ${section.explanation}
      </div>
    `;
  }

if (section.verses && section.verses.length) {
  section.verses.forEach(v => {
    html += `
      <div class="mb-10 mt-6">
        <div class="arabic-text bg-purple-50 p-6 rounded-lg mb-3">
          ${v.arabic}
        </div>
        <p class="italic text-gray-700 mb-2">${v.translation}</p>
        <p class="text-sm text-purple-600 mb-4">${v.reference}</p>

${v.audio ? `
  <div class="quran-audio-wrapper mt-4">
    <audio controls preload="metadata" class="quran-audio">
      <source src="${v.audio}" type="audio/mpeg">
      Your browser does not support the audio element.
    </audio>
  </div>
` : ""}

        ${v.explanation ? `
          <div class="story-text explanation text-gray-700">
            ${v.explanation}
          </div>
        ` : ""}
      </div>
    `;
  });
}


return html;
}


function nextPage() {
  currentPageIndex++;
  renderBookletPage();
  window.scrollTo({ top: 0, behavior: 'smooth' });
}

function prevPage() {
  currentPageIndex--;
  renderBookletPage();
  window.scrollTo({ top: 0, behavior: 'smooth' });
}

function backToStoryList() {
  const container = document.getElementById('storiesContainer');
  const selector = document.getElementById('storySelectorWrapper');

  container.innerHTML = '';
  selector.classList.remove('hidden');

  window.scrollTo({ top: 0, behavior: 'smooth' });
}

